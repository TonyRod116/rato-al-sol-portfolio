// Generate a provisional notice set from the checked-in official source texts.
// Confirm the exact native dependency graph and notices for each final binary.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const directory = path.join(root, 'mobile/src/native-notice-sources');
const sources = [
  ['OkHttp · Apache 2.0', ['okhttp-license.txt']],
  ['Okio · Apache 2.0', ['okio-license.txt']],
  ['Fresco · MIT', ['fresco-license.txt']],
  ['Folly · Apache 2.0', ['folly-license.txt']],
  // Upstream license texts match the React Native podspec references; the
  // precompiled iOS framework does not establish exact component versions.
  ['fmt · MIT', ['fmt-license.txt']],
  ['DoubleConversion · BSD 3-Clause', ['double-conversion-license.txt']],
  ['glog · BSD 3-Clause', ['glog-license.txt']],
  ['Boost · Boost Software License 1.0', ['boost-license.txt']],
  ['Hermes · MIT', ['hermes-license.txt']],
  ['Kotlin · Apache 2.0', ['kotlin-license.txt']],
  // Reference NOTICE retained for matching Codec classes; exact version is unverified.
  ['Apache Commons Codec · Apache 2.0', ['codec-notice.txt', 'codec-license.txt']],
  ['Public Suffix List · MPL 2.0', ['public-suffix-notice.txt', 'mpl-2.0.txt']],
];
const notices = sources.map(([name, files]) => ({ name, text: files.map((file) => {
  const contents = fs.readFileSync(path.join(directory, file), 'utf8').replace(/\r\n/g, '\n');
  if (!contents.trim()) throw new Error(`Empty native notice: ${file}`);
  return contents;
}).join('\n\n') }));
fs.writeFileSync(path.join(root, 'mobile/src/native-third-party-notices.mjs'),
  `// Generated by scripts/generate-native-component-notices.cjs.\nexport const NATIVE_NOTICES = ${JSON.stringify(notices, null, 2)};\n`);
console.log(`Generated ${notices.length} provisional native notices; final binaries still require audit.`);
