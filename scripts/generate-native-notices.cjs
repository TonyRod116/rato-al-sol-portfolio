// Generate notices for declared direct packages and, when provided, modules in
// an Expo iOS source map. Native dependencies still require a separate audit.
const fs = require('node:fs');
const path = require('node:path');
if (!process.argv[3]) {
  console.error('Usage: node scripts/generate-native-notices.cjs <node_modules> <iOS-source-map>');
  process.exit(1);
}
const root = path.resolve(__dirname, '..');
const modules = process.argv[2] ? path.resolve(process.argv[2]) : path.join(root, 'mobile', 'node_modules');
const direct = Object.keys(JSON.parse(fs.readFileSync(path.join(root, 'mobile/package.json'), 'utf8')).dependencies).sort();
const directories = new Set(direct.map((name) => path.join(modules, ...name.split('/'))));
if (process.argv[3]) {
  const map = JSON.parse(fs.readFileSync(process.argv[3], 'utf8'));
  for (const source of map.sources) {
    const normal = source.replace(/\\/g, '/');
    const start = normal.lastIndexOf('/node_modules/');
    if (start < 0) continue;
    const pieces = normal.slice(start + '/node_modules/'.length).split('/');
    const prefix = normal.slice(0, start).replace(/^\/+/, '');
    const packageSegments = pieces[0].startsWith('@') ? pieces.slice(0, 2) : pieces.slice(0, 1);
    directories.add(path.join(root, 'mobile', prefix, 'node_modules', ...packageSegments));
  }
}
const unique = new Map();
for (const directory of directories) {
  const pkg = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'));
  const name = pkg.name;
  const filename = fs.readdirSync(directory).find((item) => /^(licen[cs]e|copying)(\..*)?$/i.test(item));
  const noticePath = filename ? path.join(directory, filename) : name === '@react-native-community/slider'
    ? path.join(root, 'mobile/src/slider-license.txt') : name.startsWith('@react-native/') && pkg.version === '0.86.3'
      ? path.join(modules, 'react-native/LICENSE') : null;
  if (!noticePath) throw new Error(`Missing full license for ${name}@${pkg.version}`);
  unique.set(`${name}@${pkg.version}`, { name, version: pkg.version, license: pkg.license, text: fs.readFileSync(noticePath, 'utf8').replace(/\r\n/g, '\n') });
}
const notices = [...unique.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const noticeFile = path.join(root, 'mobile/src/third-party-notices.mjs');
if (fs.existsSync(noticeFile)) {
  const previous = fs.readFileSync(noticeFile, 'utf8').match(/export const DEPENDENCY_NOTICES = ([\s\S]*);\s*$/);
  if (!previous) throw new Error('Cannot verify the existing dependency notice inventory');
  const priorPackages = JSON.parse(previous[1]);
  const present = new Set(notices.map((item) => `${item.name}@${item.version}`));
  const missing = priorPackages.filter((item) => !present.has(`${item.name}@${item.version}`));
  if (missing.length) throw new Error(`Refusing to remove existing notices without review: ${missing.map((item) => `${item.name}@${item.version}`).join(', ')}`);
}
const sunCalc = fs.readFileSync(path.join(root, 'frontend/vendor/SUNCALC-LICENSE.txt'), 'utf8').replace(/\r\n/g, '\n');
const output = `// Generated by scripts/generate-native-notices.cjs.\nexport const SUNCALC_LICENSE = ${JSON.stringify(sunCalc)};\nexport const DEPENDENCY_NOTICES = ${JSON.stringify(notices, null, 2)};\n`;
fs.writeFileSync(noticeFile, output);
console.log(`Generated ${notices.length} dependency notices; native and Android audits remain necessary.`);
